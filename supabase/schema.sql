    FOR SELECT TO authenticated USING (auth.uid() = profile_id);

CREATE POLICY "Users can insert their own account details" ON public.account_details
    FOR INSERT TO authenticated WITH CHECK (auth.uid() = profile_id);

CREATE POLICY "Users can update their own account details" ON public.account_details
    FOR UPDATE TO authenticated
    USING (auth.uid() = profile_id)
    WITH CHECK (auth.uid() = profile_id);

CREATE POLICY "Allow visible profile posts to be read" ON public.posts
    FOR SELECT USING (
        auth.uid() = profile_id
        OR EXISTS (
            SELECT 1
            FROM public.profiles AS profile
            WHERE profile.id = posts.profile_id
              AND profile.is_private = false
        )
    );

CREATE POLICY "Allow authenticated users to insert posts" ON public.posts
    FOR INSERT WITH CHECK (auth.uid() = profile_id);

CREATE POLICY "Allow visible profile favorites to be read" ON public.favorites
    FOR SELECT USING (
        auth.uid() = profile_id
        OR EXISTS (
            SELECT 1
            FROM public.profiles AS profile
            WHERE profile.id = favorites.profile_id
              AND profile.is_private = false
        )
    );

CREATE POLICY "Allow authenticated users to insert/delete favorites" ON public.favorites
    FOR ALL USING (auth.uid() = profile_id);

CREATE POLICY "Allow visible profile collections to be read" ON public.collections
    FOR SELECT USING (
        auth.uid() = profile_id
        OR EXISTS (
            SELECT 1
            FROM public.profiles AS profile
            WHERE profile.id = collections.profile_id
              AND profile.is_private = false
        )
    );

CREATE POLICY "Allow authenticated users to insert/delete collections" ON public.collections
    FOR ALL USING (auth.uid() = profile_id);

CREATE POLICY "Users can read their own legal consents" ON public.legal_consents
    FOR SELECT USING (auth.uid() = profile_id);

CREATE POLICY "Users can insert their own legal consents" ON public.legal_consents
    FOR INSERT WITH CHECK (auth.uid() = profile_id);

CREATE POLICY "Anyone can submit a contact request" ON public.contact_requests
    FOR INSERT TO anon, authenticated
    WITH CHECK (
        status = 'received'
        AND (profile_id IS NULL OR auth.uid() = profile_id)
    );

