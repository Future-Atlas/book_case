    ON public.post_reactions FOR UPDATE TO authenticated
    USING (auth.uid() = profile_id AND public.is_profile_active(auth.uid()))
    WITH CHECK (
        auth.uid() = profile_id
        AND public.is_profile_active(auth.uid())
        AND EXISTS (
            SELECT 1
            FROM public.posts
            WHERE posts.id = post_reactions.post_id
              AND posts.profile_id <> auth.uid()
              AND public.can_view_profile_content(posts.profile_id)
        )
    );

