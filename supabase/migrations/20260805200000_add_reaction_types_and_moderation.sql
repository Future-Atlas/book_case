-- Typed reactions, post reporting and administrator moderation.

ALTER TABLE public.post_reactions
    ADD COLUMN IF NOT EXISTS reaction_type TEXT NOT NULL DEFAULT 'like';

ALTER TABLE public.post_reactions
    DROP CONSTRAINT IF EXISTS post_reactions_reaction_type_check;
ALTER TABLE public.post_reactions
    ADD CONSTRAINT post_reactions_reaction_type_check
    CHECK (reaction_type IN ('like', 'love', 'sad'));

ALTER TABLE public.profiles
    ADD COLUMN IF NOT EXISTS is_suspended BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS public.app_admins (
    profile_id UUID PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE TABLE IF NOT EXISTS public.account_suspensions (
    profile_id UUID PRIMARY KEY REFERENCES public.profiles(id) ON DELETE CASCADE,
    reason TEXT,
    suspended_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
    suspended_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL
);

CREATE TABLE IF NOT EXISTS public.moderation_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    reported_profile_id UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    post_id UUID REFERENCES public.posts(id) ON DELETE SET NULL,
    category TEXT NOT NULL CHECK (
        category IN ('spam', 'harassment', 'bullying', 'offensive', 'other')
    ),
    details TEXT CHECK (details IS NULL OR char_length(details) <= 1000),
    post_snapshot JSONB NOT NULL DEFAULT '{}'::jsonb,
    status TEXT NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'resolved')),
    resolution TEXT,
    resolved_by UUID REFERENCES public.profiles(id) ON DELETE SET NULL,
    resolved_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS moderation_reports_open_unique
    ON public.moderation_reports (reporter_id, post_id)
    WHERE status = 'open' AND post_id IS NOT NULL;
CREATE INDEX IF NOT EXISTS moderation_reports_status_created_idx
    ON public.moderation_reports (status, created_at DESC);
CREATE INDEX IF NOT EXISTS moderation_reports_profile_idx
    ON public.moderation_reports (reported_profile_id, created_at DESC);

ALTER TABLE public.app_admins ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.account_suspensions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.moderation_reports ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.is_current_user_admin()
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1 FROM public.app_admins WHERE profile_id = auth.uid()
    );
$$;

CREATE OR REPLACE FUNCTION public.is_profile_active(profile UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT CASE
        WHEN profile IS NULL THEN true
        ELSE COALESCE((
            SELECT NOT is_suspended FROM public.profiles WHERE id = profile
        ), false)
    END;
$$;

CREATE OR REPLACE FUNCTION public.can_view_profile_content(owner_profile UUID)
RETURNS BOOLEAN
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = public
AS $$
    SELECT EXISTS (
        SELECT 1
        FROM public.profiles AS owner
        WHERE owner.id = owner_profile
          AND owner.is_suspended = false
          AND public.is_profile_active(auth.uid())
          AND (
              auth.uid() = owner.id
              OR (
                  NOT public.is_blocked_between(auth.uid(), owner.id)
                  AND (
                      owner.is_private = false
                      OR EXISTS (
                          SELECT 1
                          FROM public.follows
                          WHERE follower_id = auth.uid()
                            AND following_id = owner.id
                            AND status = 'accepted'
                      )
                  )
              )
          )
    );
$$;

